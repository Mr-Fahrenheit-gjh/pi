export async function runBrowserChecks(page, options) {
  const checks = [], errors = [];
  const assert = (value, message) => { if (!value) throw new Error(message); checks.push(message); };
  page.on("pageerror", error => errors.push(error.message));
  let sent = 0;
  page.on("request", request => {
    if (request.method() !== "POST" || !/\/api\/agent\/suggestions-[ab]$/.test(request.url())) return;
    try { const data = request.postDataJSON(); if (data.type === "prompt" && !data.message.startsWith("/fixture-suggestion")) sent++; } catch {}
  });
  await page.setViewportSize({ width: 1280, height: 900 });
  await page.addInitScript(() => localStorage.setItem("pi-locale", "zh-CN"));
  await page.route("**/api/agent/*/subagents**", route => route.fulfill({json:{available:false}}));
  await page.goto(`${options.baseURL}/?session=suggestions-a`, { waitUntil: "domcontentloaded" });
  const input = page.locator(".chat-content textarea.chat-input-textarea").first();
  const ghost = page.locator("textarea[data-prompt-suggestion]");
  const frame = () => page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  const fixture = async (sessionId, args = "show") => {
    const response = await page.request.post(`${options.baseURL}/api/agent/${sessionId}`, { data: {type:"prompt",message:`/fixture-suggestion ${args}`} });
    if (!response.ok()) throw new Error(`fixture command HTTP ${response.status()}: ${await response.text()}`);
    const body = await response.json(); if (body.success === false || body.error) throw new Error(JSON.stringify(body));
  };
  const send = async (text) => { await input.fill(text); await input.press("Enter"); await ghost.waitFor(); };
  await input.waitFor();
  assert(await ghost.count() === 0, "Opening finished history does not generate a suggestion");
  await send("开始候选验证");
  assert(await input.inputValue() === "", "Real SDK run completes with an empty composer");
  assert((await input.getAttribute("placeholder")).includes("帮我运行相关测试"), "Real extension model result reaches the Web ghost placeholder");
  const firstId = await ghost.getAttribute("data-prompt-suggestion");
  await page.screenshot({ path: `${options.outputDir}/ghost.png`, fullPage: true });
  const beforeTab = sent;
  await input.press("Tab");
  assert(await input.inputValue() === "帮我运行相关测试", "Tab accepts the Chinese suggestion");
  await frame();
  assert(sent === beforeTab, "Tab does not send a prompt");
  await input.press("Enter");
  await ghost.waitFor();
  assert((await ghost.getAttribute("data-prompt-suggestion")) !== firstId, "A new completed run produces a new suggestion identity");
  const beforeEnter = sent;
  await input.press("Enter"); await frame();
  assert(sent === beforeEnter && await input.inputValue() === "", "Enter on empty ghost text never submits it");
  await input.press("Escape");
  await page.waitForFunction(() => !document.querySelector("textarea[data-prompt-suggestion]"));
  assert(await input.inputValue() === "", "Escape dismisses without changing the draft");
  await input.fill("我自己的草稿");
  await fixture("suggestions-a"); await frame();
  assert(await input.inputValue() === "我自己的草稿" && await ghost.count() === 0, "A late suggestion never overwrites a draft");
  await input.fill(""); await frame();
  assert(await ghost.count() === 0, "Clearing a draft does not resurrect the dismissed late suggestion");
  await fixture("suggestions-a"); await ghost.waitFor();
  await input.dispatchEvent("compositionstart");
  await input.dispatchEvent("keydown", {key:"Tab",code:"Tab",isComposing:true,keyCode:229});
  assert(await input.inputValue() === "", "IME Tab never accepts ghost text");
  await input.dispatchEvent("compositionend");
  await fixture("suggestions-a"); await ghost.waitFor();
  await input.fill("/fi"); await frame();
  assert(await ghost.count() === 0, "Slash-command entry keeps its own completion instead of a ghost suggestion");
  await input.press("Escape"); await input.fill("");
  await fixture("suggestions-a"); await ghost.waitFor();
  await page.locator('a.session-tree-main[href="?session=suggestions-b"]').click();
  await page.getByText("已完成的测试历史 b", {exact:true}).waitFor();
  assert(await ghost.count() === 0 && await input.inputValue() === "", "Switching sessions cannot show another session's suggestion");
  await send("第二个会话候选验证");
  await fixture("suggestions-b", "wrong-session");
  await page.waitForFunction(() => !document.querySelector("textarea[data-prompt-suggestion]"));
  assert(await ghost.count() === 0, "The widget payload's session owner is checked before rendering");
  await fixture("suggestions-b", "no-tab");
  await page.waitForFunction(() => document.querySelector("textarea[data-prompt-suggestion]")?.getAttribute("placeholder")?.endsWith("→"));
  const beforeDisabledTab = sent;
  await input.focus(); await input.press("Tab"); await frame();
  assert(await input.inputValue() === "" && sent === beforeDisabledTab, "acceptTab:false leaves Tab native and never sends");
  await input.focus(); await input.press("ArrowRight");
  assert(await input.inputValue() === "帮我运行相关测试", "Right Arrow accepts when Tab acceptance is disabled");
  await input.fill("");
  await fixture("suggestions-b");
  await page.waitForFunction(() => document.querySelector("textarea[data-prompt-suggestion]")?.getAttribute("placeholder")?.endsWith("Tab"));
  await input.focus(); await input.press("Tab");
  await page.locator('a.session-tree-main[href="?session=suggestions-a"]').click();
  await page.getByText("已完成的测试历史 a", {exact:true}).waitFor();
  await page.locator('a.session-tree-main[href="?session=suggestions-b"]').click();
  await page.getByText("已完成的测试历史 b", {exact:true}).waitFor();
  assert(await input.inputValue() === "帮我运行相关测试", "Accepted text survives session switching as an ordinary unsent draft");
  assert(errors.length === 0, `No browser errors (${errors.length})`);
  return { passed: true, checks, pageErrors: errors, sentPrompts: sent };
}
