import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import test from "node:test";
import {createJiti} from "jiti";
const jiti=createJiti(import.meta.url,{tsconfigPaths:true});
const {withSafeChatAttachmentRoot,isExistingFilePathAllowed}=await jiti.import("./file-access.ts");
test("cached/extra attachment grants cannot survive a symlink root replacement",(t)=>{
 const root=fs.mkdtempSync(path.join(os.tmpdir(),"pi-attachment-access-"));
 t.after(()=>fs.rmSync(root,{recursive:true,force:true}));
 const agent=path.join(root,"agent"),attachments=path.join(agent,"chat-attachments"),outside=path.join(root,"outside");
 fs.mkdirSync(attachments,{recursive:true});fs.mkdirSync(outside);
 fs.writeFileSync(path.join(outside,"private.txt"),"private");
 const cached=new Set([attachments,path.join(attachments,"nested")]);
 assert.equal(withSafeChatAttachmentRoot(cached,agent).has(attachments),true);
 fs.rmdirSync(attachments);fs.symlinkSync(outside,attachments);
 const allowed=withSafeChatAttachmentRoot(cached,agent);
 assert.equal(allowed.has(attachments),false);
 assert.equal(allowed.has(path.join(attachments,"nested")),false);
 assert.equal(isExistingFilePathAllowed(path.join(attachments,"private.txt"),allowed),false);
});
